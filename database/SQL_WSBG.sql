CREATE TABLE VOUCHER (
    maVoucher          VARCHAR(30)   NOT NULL,        
    tenVoucher         NVARCHAR(150) NOT NULL,
    loaiGiam           VARCHAR(20)   NOT NULL,        
    giaTriGiam         DECIMAL(18,2) NOT NULL,
    giamToiDa          DECIMAL(18,2) NULL,            
    donToiThieu        DECIMAL(18,2) NOT NULL CONSTRAINT DF_VOUCHER_donToiThieu DEFAULT 0,
    ngayBatDau         DATE          NOT NULL,
    ngayKetThuc        DATE          NOT NULL,
    ngayPhatHanh       DATE          NOT NULL,
    doiTuongSuDung     VARCHAR(20)   NOT NULL,    
    soLuongPhatHanh    INT           NOT NULL,       
    soLuongMoiTaiKhoan INT           NOT NULL CONSTRAINT DF_VOUCHER_soLuongMoiTaiKhoan DEFAULT 1,
    mucCanhBaoSoLuong  INT           NOT NULL CONSTRAINT DF_VOUCHER_mucCanhBaoSoLuong DEFAULT 0,
    trangThai          NVARCHAR(30)  NOT NULL,        
    maNhanVien         VARCHAR(20)   NOT NULL,
    CONSTRAINT PK_VOUCHER PRIMARY KEY (maVoucher),
    CONSTRAINT CK_VOUCHER_loaiGiam CHECK (loaiGiam IN ('PHAN_TRAM', 'SO_TIEN')),
    CONSTRAINT CK_VOUCHER_doiTuongSuDung CHECK (doiTuongSuDung IN ('TAT_CA', 'NHAP_MA')),
    CONSTRAINT CK_VOUCHER_giaTriGiam CHECK (giaTriGiam > 0 AND (loaiGiam <> 'PHAN_TRAM' OR giaTriGiam <= 100)),
    CONSTRAINT CK_VOUCHER_ngay CHECK (ngayKetThuc >= ngayBatDau),
    CONSTRAINT CK_VOUCHER_soLuong CHECK (soLuongPhatHanh >= 0 AND soLuongMoiTaiKhoan >= 1),
    CONSTRAINT FK_VOUCHER_NHANVIEN FOREIGN KEY (maNhanVien) REFERENCES NHANVIEN(maNhanVien)
);


