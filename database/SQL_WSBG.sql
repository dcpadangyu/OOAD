    CONSTRAINT CK_CHITIETGIOHANG_donGia CHECK (donGia >= 0),
    CONSTRAINT FK_CHITIETGIOHANG_GIOHANG     FOREIGN KEY (maGioHang)   REFERENCES GIOHANG(maGioHang) ON DELETE CASCADE,
